-- 012_motor_iso_class.sql
-- เติมกำลังมอเตอร์ และแก้เกณฑ์ Warning ให้ตรงคลาส ISO
--
-- ยืนยันหน้างาน 2026-09-17: มอเตอร์ทั้ง 4 ตัวเป็น 11 kW เหมือนกันหมด
--
-- ค่าเริ่มต้นเดิม 2.800/4.500 มาจาก ISO 20816-3 Group 2 ซึ่งใช้กับเครื่อง 15–300 kW
-- 11 kW อยู่นอกขอบเขตนั้น ต้องใช้ ISO 10816-1 Class I (เครื่องไม่เกิน 15 kW) แทน
--   A/B  0.71 mm/s
--   B/C  1.80 mm/s  <- Warning
--   C/D  4.50 mm/s  <- Alarm (บังเอิญเท่าเดิม ไม่ต้องแก้)
--
-- ผลคือช่วง 1.8–2.8 mm/s เปลี่ยนจาก "เงียบ" เป็น "เตือน" ซึ่งเป็นช่วงที่เครื่อง
-- เริ่มผิดปกติแต่ยังไม่อันตราย — ช่วงที่มีค่าที่สุดสำหรับการซ่อมบำรุงเชิงพยากรณ์
--
-- iso_group ปล่อย NULL ไว้ตามเดิม: ยังไม่มีโค้ดตรงไหนอ่านมันเลย (ส่งผ่าน API เฉย ๆ)
-- และ SMALLINT ตัวเดียวแยกไม่ออกว่าหมายถึง Group ของ 20816-3 หรือ Class ของ 10816-1
-- ถ้าวันหนึ่งต้องใช้จริง ค่อยเปลี่ยนเป็น enum ที่บอกทั้งมาตรฐานและคลาส

-- ── UP ──────────────────────────────────────────────────────
-- แตะเฉพาะแถวที่ยังไม่เคยตั้งกำลังไว้ — รันซ้ำไม่เปลี่ยนอะไร และไม่ทับค่าที่ admin แก้เองทีหลัง
UPDATE motors
   SET rated_kw          = 11,
       warning_threshold = 1.800
 WHERE rated_kw IS NULL;

