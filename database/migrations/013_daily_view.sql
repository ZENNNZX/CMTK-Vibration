-- 013 · v_motor_daily — ค่าเฉลี่ยรายวัน "เฉพาะนาทีที่เครื่องเดิน"
--
-- ทำไมต้องมี: readings_minute เก็บทุกนาทีรวมชั่วโมงที่เครื่องดับ การเฉลี่ยทั้งวัน
-- จึงเป็นค่าผสมระหว่างเครื่องเดินกับเครื่องหยุด ซึ่งไม่ใช่สภาพของเครื่องในทั้งสองแบบ
--
-- วัดจริง 2026-09-22 (MOTOR-04 · ข้อมูล 116 วัน):
--   89,032 นาที อยู่ที่ 0.03–0.20 mm/s   <- เครื่องหยุด
--    1,320 นาที อยู่ที่ 0.20–0.40 mm/s   <- หุบเขาระหว่างสองกอง
--   ที่เหลือ    อยู่ที่ 0.40–7.20 mm/s   <- เครื่องเดิน
-- ตัดที่ 0.2 mm/s จึงแยกสองกองได้สะอาด โดยไม่ต้องเดา
--
-- ผลของการไม่กรอง: ค่าเฉลี่ยรายวันของ MOTOR-04 ตกจาก 1.22–2.18 เหลือ 0.30–0.95
-- โมเดลจึงทำนายได้ 0.46 mm/s ขณะที่เครื่องเดินจริงอยู่ที่ 2.24 (โซน C เกิน Warning)
--
-- 0.2 mm/s เป็นปุ่มปรับหน้างาน ไม่ใช่ค่าสากล — มอเตอร์รุ่นอื่นหรือจุดวัดอื่น
-- กองของ "เครื่องหยุด" อยู่คนละที่ ก่อนย้ายเกณฑ์ให้ดูฮิสโตแกรมของเครื่องนั้นก่อน
--
-- view นี้คือ "นิยามเดียว" ของคำว่าเครื่องกำลังเดิน — ทั้ง backend (Node) และงาน ML
-- ต้องอ่านจากที่นี่ ห้ามเขียนเกณฑ์ซ้ำที่อื่น
--
-- rollback:
--   DROP VIEW IF EXISTS v_motor_daily;

CREATE OR REPLACE VIEW v_motor_daily AS
SELECT motor_id,
       (minute_ts AT TIME ZONE 'Asia/Bangkok')::date AS day,
       AVG(vrms_y_avg)      AS vrms_y,
       AVG(vrms_z_avg)      AS vrms_z,
       AVG(temperature_avg) AS temperature,
       COUNT(*)             AS n_running
  FROM readings_minute
 WHERE vrms_y_avg >= 0.2
 GROUP BY 1, 2;

COMMENT ON VIEW v_motor_daily IS
  'ค่าเฉลี่ยรายวันตามปฏิทินไทย นับเฉพาะนาทีที่ vrms_y_avg >= 0.2 mm/s (เครื่องเดิน) · ดูเหตุผลใน 013_daily_view.sql';
